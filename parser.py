# ── Dynamic section detection ──────────────────────────────────────────────────

def _find_header(lines: list, marker: str, validator: str,
                 start: int = 0, window: int = 80) -> int:
    """
    Find the real financial statement header (not a TOC reference) by requiring:
    - A line containing `marker` (short line, < 60 chars)
    - `validator` to appear within `window` lines after it
    Returns line index or -1.
    """
    m, v = marker.lower(), validator.lower()
    for i in range(start, len(lines)):
        if m in lines[i].lower() and len(lines[i]) < 60:
            ctx = " ".join(lines[i : i + window]).lower()
            if v in ctx:
                return i
    return -1


def detect_sections(company: str, lines: list) -> dict:
    """
    Dynamically locate income statement, balance sheet, and cash flow statement
    sections within the filing. Returns {section: (start_line, end_line)}.
    """
    if company == "Google":
        # Google filing order: balance sheet → income statement → cash flows
        balance  = _find_header(lines, "CONSOLIDATED BALANCE SHEETS",       "total assets")
        income   = _find_header(lines, "CONSOLIDATED STATEMENTS OF INCOME", "revenues",           start=balance)
        cashflow = _find_header(lines, "CONSOLIDATED STATEMENTS OF CASH FLOWS", "operating activities", start=income)
        return {
            "balance":  (balance,  income),
            "income":   (income,   cashflow),
            "cashflow": (cashflow, cashflow + 400),
        }
    elif company == "Apple":
        # Apple filing order: income statement → balance sheet → cash flows
        balance  = _find_header(lines, "CONSOLIDATED BALANCE SHEETS",           "cash",        window=80)
        cashflow = _find_header(lines, "CONSOLIDATED STATEMENTS OF CASH FLOWS", "depreciation")
        return {
            "income":   (max(0, balance - 500), balance),
            "balance":  (balance,  cashflow),
            "cashflow": (cashflow, cashflow + 400),
        }
    else:  # Microsoft
        # Microsoft filing order: income statement → balance sheet → cash flows
        # Headers are short single words ("BALANCE", "CASH FLOWS S")
        balance  = _find_header(lines, "BALANCE",    "total assets")
        cashflow = _find_header(lines, "CASH FLOWS", "net income",  start=balance)
        return {
            "income":   (max(0, balance - 200), balance),
            "balance":  (balance,  cashflow),
            "cashflow": (cashflow, cashflow + 400),
        }


